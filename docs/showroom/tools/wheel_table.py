"""Print the Swift wheel table (TeslaWheel cases, assets, caps swaps, Fleet names) from the Tesla
app's VehicleOptions.gd, using the same asset names as export_wheels.py."""
import re, sys
from export_wheels import asset_name
src = open(sys.argv[1] if len(sys.argv) > 1 else '/workspace/tesla-apk-latest/gdre/VehicleOptions.gd').read()
def block(name):
    b = src.split('const ' + name)[1]; return b[:b.index('\n}')]
enum = re.findall(r'\w+', src.split('enum WheelType{')[1].split('}')[0])  # the decompile drops a comma after PinwheelRefresh
paths = dict(re.findall(r'WheelType\.(\w+): NodePath\("([^"]+)"\)', block('WheelTypeToPathMap')))
caps = {k: (v == 'true', p) for k, v, p in re.findall(r'WheelType\.(\w+): \[(true|false), NodePath\("([^"]+)"\)\]', block('WheelTypeToCapsOverrideMap'))}
mobile = re.findall(r'"(\w+)": WheelType\.(\w+)', block('MobileWheelTypeEnumMap'))
gtw = re.findall(r'"(\w+)": WheelType\.(\w+)', block('GTWWheelTypeEnumMap'))
skip = {k for k, p in paths.items() if not p.endswith('.tscn') or 'Cybercab' in p}
def case(n):
    s = n.replace('_', ''); return s[0].lower() + s[1:]
# Tesla has two enum names for the Apollo 19 Metallic Shadow; both point at the same scene.
alias = {}
seen = {}
for n in enum:
    if n not in paths or n in skip: continue
    c = case(n)
    if c in seen:
        assert paths[seen[c]] == paths[n] and caps.get(seen[c]) == caps.get(n), n
        alias[n] = seen[c]; continue
    seen[c] = n
def canon(n): return alias.get(n, n)
out = []
out.append('    // Generated by docs/showroom/tools/wheel_table.py from VehicleOptions.gd (Tesla app 4.62.5).')
out.append('    // swiftlint:disable identifier_name')
for c, n in seen.items(): out.append(f'    case {c} = "{n}"')
out.append('')
out.append('    /// usdz in TeslaAssets (WheelTypeToPathMap).')
out.append('    var asset: String {')
out.append('        switch self {')
for c, n in seen.items(): out.append(f'        case .{c}: return "{asset_name(paths[n])}"')
out.append('        }\n    }')
out.append('')
out.append('    /// WheelTypeToCapsOverrideMap: when the caps state equals `whenCapsOn`, Tesla draws `asset` instead.')
out.append('    var capsSwap: (whenCapsOn: Bool, asset: String)? {')
out.append('        switch self {')
for c, n in seen.items():
    if n in caps: out.append(f'        case .{c}: return ({str(caps[n][0]).lower()}, "{asset_name(caps[n][1])}")')
out.append('        default: return nil')
out.append('        }\n    }')
out.append('')
out.append('    /// Fleet `vehicle_config.wheel_type` (MobileWheelTypeEnumMap), then the car\'s own names')
out.append('    /// (GTWWheelTypeEnumMap) where Fleet has none, keyed lowercase with only letters and digits.')
out.append('    static let fleetNames: [String: TeslaWheel] = [')
keys = {}
for k, v in mobile + gtw:
    v = canon(v)
    if v in skip or v not in paths: continue
    nk = re.sub(r'[^a-z0-9]', '', k.lower())
    if nk in keys: continue
    if nk == 'unknown': continue  # an unknown wheel uses the car's own default, not Stiletto
    keys[nk] = v
for nk, v in keys.items(): out.append(f'        "{nk}": .{case(v)},')
out.append('    ]')
out.append('    // swiftlint:enable identifier_name')
print('\n'.join(out))
assets = sorted({asset_name(paths[n]) for n in seen.values()} | {asset_name(p) for k, (f, p) in caps.items() if canon(k) in seen.values()})
print('// ASSETS', len(assets), ' '.join(assets), file=sys.stderr)
